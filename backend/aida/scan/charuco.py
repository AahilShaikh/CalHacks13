"""ChArUco turntable calibration: board configuration, pose, and inspection.

Board geometry matches the printable boards generated by :mod:`aida.scan.boards`
(DICT_5X5_100, 20.0 mm squares, 15.0 mm markers). The turntable board is a
10x10 grid covering the 8-inch (203.2 mm) disc; the rectangular boards are
10x13 (US Letter) and 10x14 (A4).

Detection solves the camera pose relative to the turntable ground plane (Z=0)
and estimates the ground-plane resolution in pixels per millimeter from the
known square size. Pose and scale are reported as data; this module never
prints, so callers decide how to surface failures.
"""
import cv2
import numpy as np

# ChArUco board configuration shared with aida.scan.boards.
SQUARES_X = 10
SQUARES_Y = 10
SQUARE_LENGTH_MM = 20.0
MARKER_LENGTH_MM = 15.0
DICTIONARY = cv2.aruco.DICT_5X5_100

BOARD_PRESETS = {
    'turntable': (SQUARES_X, SQUARES_Y),
    'rectangular_letter': (10, 13),
    'rectangular_a4': (10, 14),
}


class CalibrationError(RuntimeError):
    """Raised when the ChArUco board cannot be detected or posed."""


def make_board(squares_x=SQUARES_X, squares_y=SQUARES_Y):
    """Build the ChArUco board and its marker dictionary (coordinates in meters)."""
    dictionary = cv2.aruco.getPredefinedDictionary(DICTIONARY)
    board = cv2.aruco.CharucoBoard(
        size=(squares_x, squares_y),
        squareLength=SQUARE_LENGTH_MM / 1000.0,
        markerLength=MARKER_LENGTH_MM / 1000.0,
        dictionary=dictionary,
    )
    return board, dictionary


def estimate_camera_matrix(img_w, img_h, f_equiv_35mm=26.0):
    """Approximate intrinsic camera matrix K from image size and a ~26 mm phone lens.

    For a standard 35 mm full-frame sensor (36 mm width):
    fx = (f_equiv_35mm / 36.0) * max(w, h).
    """
    fx = (f_equiv_35mm / 36.0) * max(img_w, img_h)
    K = np.array([
        [fx, 0, img_w / 2.0],
        [0, fx, img_h / 2.0],
        [0, 0, 1],
    ], dtype=np.float64)
    dist_coeffs = np.zeros((5, 1), dtype=np.float64)
    return K, dist_coeffs


def detect_charuco_ground_plane(image_path, K=None, dist_coeffs=None,
                                squares_x=SQUARES_X, squares_y=SQUARES_Y):
    """Detect the ChArUco board and solve camera pose over the turntable plane.

    Returns a dict with the Rodrigues rotation ``rvec``/``R``, translation
    ``tvec`` (board coordinates, meters), intrinsics ``K``, ``dist_coeffs``,
    ``px_per_mm_ground`` (median pixels-per-mm between adjacent detected
    corners) and ``num_corners_detected``. Raises :class:`CalibrationError`
    when fewer than four corners are visible or PnP fails.
    """
    img = cv2.imread(str(image_path))
    if img is None:
        raise FileNotFoundError(f'Could not load image: {image_path}')

    h, w = img.shape[:2]
    if K is None:
        K, dist_coeffs = estimate_camera_matrix(w, h)

    board, _ = make_board(squares_x, squares_y)
    detector = cv2.aruco.CharucoDetector(board)
    charuco_corners, charuco_ids, _, _ = detector.detectBoard(img)

    if charuco_ids is None or len(charuco_ids) < 4:
        found = 0 if charuco_ids is None else len(charuco_ids)
        raise CalibrationError(
            f'Only {found} ChArUco corners detected in {image_path}. '
            f'Need at least 4 visible corners around the object base to calibrate pose.')

    all_obj_points = board.getChessboardCorners()
    obj_points = all_obj_points[charuco_ids.flatten()]
    img_points = charuco_corners.reshape(-1, 2)

    success, rvec, tvec = cv2.solvePnP(
        obj_points, img_points, K, dist_coeffs, flags=cv2.SOLVEPNP_ITERATIVE)
    if not success:
        raise CalibrationError('PnP solver failed to find the turntable pose.')

    R, _ = cv2.Rodrigues(rvec)

    # Ground-plane resolution from adjacent detected corners: each neighbouring
    # corner pair in the grid is exactly SQUARE_LENGTH_MM apart.
    ids_flat = charuco_ids.flatten()
    corner_cols = squares_x - 1
    diffs = []
    for i in range(len(ids_flat)):
        row_i, col_i = int(ids_flat[i]) // corner_cols, int(ids_flat[i]) % corner_cols
        for j in range(i + 1, len(ids_flat)):
            row_j, col_j = int(ids_flat[j]) // corner_cols, int(ids_flat[j]) % corner_cols
            if ((row_i == row_j and abs(col_i - col_j) == 1) or
                    (col_i == col_j and abs(row_i - row_j) == 1)):
                px_dist = np.linalg.norm(img_points[i] - img_points[j])
                diffs.append(px_dist / SQUARE_LENGTH_MM)

    return {
        'rvec': rvec,
        'tvec': tvec,
        'R': R,
        'K': K,
        'dist_coeffs': dist_coeffs,
        'px_per_mm_ground': float(np.median(diffs)) if diffs else 10.0,
        'num_corners_detected': int(len(charuco_ids)),
        'camera_distance_mm': float(np.linalg.norm(tvec) * 1000.0),
    }


def inspect_image(image_path, output_path, board='turntable',
                  squares_x=None, squares_y=None):
    """Detect markers/corners on a photo, annotate it, and return a report dict.

    Draws ArUco markers, ChArUco corners, and the 3D board axes on the image
    saved to ``output_path``. This is a debugging aid for capture setup.
    """
    img = cv2.imread(str(image_path))
    if img is None:
        raise FileNotFoundError(f'Could not load image: {image_path}')

    h, w = img.shape[:2]
    default_x, default_y = BOARD_PRESETS.get(board, BOARD_PRESETS['turntable'])
    sx = squares_x or default_x
    sy = squares_y or default_y

    board_obj, _ = make_board(sx, sy)
    detector = cv2.aruco.CharucoDetector(board_obj)
    charuco_corners, charuco_ids, marker_corners, marker_ids = detector.detectBoard(img)

    annotated = img.copy()
    report = {
        'image': str(image_path),
        'width': int(w),
        'height': int(h),
        'board': board,
        'grid': [sx, sy],
        'marker_ids': [],
        'corner_ids': [],
        'camera_distance_mm': None,
    }

    if marker_ids is not None and len(marker_ids) > 0:
        cv2.aruco.drawDetectedMarkers(annotated, marker_corners, marker_ids)
        report['marker_ids'] = [int(i) for i in marker_ids.flatten()]

    if charuco_ids is not None and len(charuco_ids) > 0:
        cv2.aruco.drawDetectedCornersCharuco(
            annotated, charuco_corners.reshape(-1, 1, 2), charuco_ids.flatten(), (255, 0, 0))
        ids_flat = charuco_ids.flatten()
        report['corner_ids'] = [int(i) for i in ids_flat]

        all_3d = board_obj.getChessboardCorners()
        samples = []
        for i in range(min(4, len(ids_flat))):
            cid = int(ids_flat[i])
            pt_3d = all_3d[cid] * 1000.0
            pt_2d = charuco_corners.reshape(-1, 2)[i]
            samples.append({'corner_id': cid,
                            'xyz_mm': [float(v) for v in pt_3d],
                            'px': [float(v) for v in pt_2d]})
        report['sample_corners'] = samples

        fx = 1.2 * max(w, h)
        K = np.array([[fx, 0, w / 2.0], [0, fx, h / 2.0], [0, 0, 1]], dtype=np.float64)
        dist_coeffs = np.zeros((5, 1), dtype=np.float64)
        obj_points = all_3d[ids_flat]
        img_points = charuco_corners.reshape(-1, 2)
        success, rvec, tvec = cv2.solvePnP(obj_points, img_points, K, dist_coeffs)
        if success:
            report['camera_distance_mm'] = float(np.linalg.norm(tvec) * 1000.0)
            cv2.drawFrameAxes(annotated, K, dist_coeffs, rvec, tvec, 0.05, 3)

    cv2.imwrite(str(output_path), annotated)
    report['annotated_image'] = str(output_path)
    return report
